const fs = require('node:fs');
const assert = require('node:assert/strict');
const gradle = fs.readFileSync('app/build.gradle.kts', 'utf8');
const strings = fs.readFileSync('app/src/main/res/values/strings.xml', 'utf8');
const stringsVi = fs.readFileSync('app/src/main/res/values-vi/strings.xml', 'utf8');
const manifest = fs.readFileSync('app/src/main/AndroidManifest.xml', 'utf8');
const mainLayout = fs.readFileSync('app/src/main/res/layout/activity_main.xml', 'utf8');
const settings = fs.readFileSync('app/src/main/java/com/carhud/aaproxy/SettingsActivity.kt', 'utf8');
const license = fs.readFileSync('app/src/main/java/com/carhud/aaproxy/LicenseManager.kt', 'utf8');
const versionCode = Number(gradle.match(/versionCode = (\d+)/)?.[1] || 0);
const versionName = gradle.match(/versionName = "([^"]+)"/)?.[1] || '';
assert.ok(versionCode >= 240);
assert.ok(/^1\.0\./.test(versionName));
assert.match(gradle, /TTube_v\$\{variant.versionName\}_\$\{variant.buildType.name\}\.apk/);
assert.match(strings, /<string name="app_name">T Tube<\/string>/);
assert.match(stringsVi, /<string name="app_name">T Tube<\/string>/);
assert.match(manifest, /android:label="T Tube"/);
assert.match(manifest, /android:label="T Tube Media"/);
assert.match(mainLayout, /contentDescription="T Tube"/);
assert.match(settings, /T Tube/);
assert.match(license, /TTUBE-/);
console.log('PASS v1.0.53: T Tube branding + launcher artifact rename');
