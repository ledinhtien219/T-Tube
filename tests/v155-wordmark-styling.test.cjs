const fs = require('node:fs');
const assert = require('node:assert/strict');
const gradle = fs.readFileSync('app/build.gradle.kts', 'utf8');
const activation = fs.readFileSync('app/src/main/java/com/carhud/aaproxy/ActivationActivity.kt', 'utf8');
const layout = fs.readFileSync('app/src/main/res/layout/activity_main.xml', 'utf8');
const branding = fs.readFileSync('app/src/main/res/values/strings.xml', 'utf8');
const versionCode = Number(gradle.match(/versionCode = (\d+)/)?.[1] || 0);
const versionName = gradle.match(/versionName = "([^"]+)"/)?.[1] || '';
assert.ok(versionCode >= 242);
assert.ok(/^1\.0\./.test(versionName));
assert.match(activation, /LinearLayout\.LayoutParams\(dp\(172\), dp\(52\)\)/);
assert.match(activation, /setImageResource\(R\.drawable\.thtv_wordmark\)/);
assert.match(layout, /android:layout_width="148dp"/);
assert.match(layout, /android:layout_height="36dp"/);
assert.match(layout, /android:src="@drawable\/thtv_wordmark"/);
assert.match(branding, /T Tube/);
console.log('PASS wordmark styling: stylized T Tube wordmark is wired into app headers');
