const fs = require('node:fs');
const assert = require('node:assert/strict');
const gradle = fs.readFileSync('app/build.gradle.kts', 'utf8');
const manifest = fs.readFileSync('app/src/main/AndroidManifest.xml', 'utf8');
const media = fs.readFileSync('app/src/main/java/com/carhud/aaproxy/CarMediaBrowserService.kt', 'utf8');
const launcherFg = fs.readFileSync('app/src/main/res/drawable/ic_launcher_foreground.xml', 'utf8');
const versionCode = Number(gradle.match(/versionCode = (\d+)/)?.[1] || 0);
const versionName = gradle.match(/versionName = "([^"]+)"/)?.[1] || "";
assert.ok(versionCode >= 243);
assert.ok(/^1\.0\./.test(versionName));
assert.match(manifest, /android:name="com\.carhud\.aaproxy\.CarHudProjectionService"[\s\S]*android:icon="@drawable\/ic_carhud_logo"/);
assert.match(manifest, /android:name="com\.carhud\.aaproxy\.CarMediaBrowserService"[\s\S]*android:icon="@drawable\/ic_carhud_media_round"/);
assert.match(manifest, /android:resource="@drawable\/ic_carhud_media_round"/);
assert.match(media, /R\.drawable\.ic_carhud_media_round/);
assert.match(launcherFg, /android:width="(?:88|104)dp" android:height="(?:88|104)dp"/);
assert.ok(fs.existsSync('app/src/main/res/drawable/ic_carhud_logo.png'));
assert.ok(fs.existsSync('app/src/main/res/drawable/ic_carhud_media_round.png'));
console.log('PASS AA icons: main/media icons use circular T Tube branding');
